import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const output = execFileSync("supabase", ["status", "-o", "env"], {
  encoding: "utf8",
  cwd: new URL("..", import.meta.url),
});

const values = {};
for (const line of output.split("\n")) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith("#")) {
    continue;
  }
  const separator = trimmed.indexOf("=");
  if (separator === -1) {
    continue;
  }
  const key = trimmed.slice(0, separator);
  let value = trimmed.slice(separator + 1);
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    value = value.slice(1, -1);
  }
  values[key] = value;
}

const url = values.API_URL || values.SUPABASE_URL;
const anon = values.ANON_KEY || values.SUPABASE_ANON_KEY;
const service = values.SERVICE_ROLE_KEY || values.SUPABASE_SERVICE_ROLE_KEY;
const database = values.DB_URL || values.DATABASE_URL;

if (!url || !anon || !service || !database) {
  console.error("supabase status did not return the local URL, anon key, service role key, and database URL.");
  console.error(`Keys seen: ${Object.keys(values).join(", ") || "(none)"}`);
  process.exit(1);
}

const file = [
  "# Generated by npm run env:local. Local keys only. Do not commit.",
  `NEXT_PUBLIC_SUPABASE_URL=${url}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}`,
  `SUPABASE_SERVICE_ROLE_KEY=${service}`,
  `DATABASE_URL=${database}`,
  "",
].join("\n");

writeFileSync(new URL("../.env.local", import.meta.url), file);
console.log("Wrote .env.local from the local Supabase stack. This file is gitignored.");
